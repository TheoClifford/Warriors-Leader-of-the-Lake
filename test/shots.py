import asyncio, pathlib
from playwright.async_api import async_playwright
ROOT = pathlib.Path('/home/claude/game'); OUT = ROOT / 'test/shots'; OUT.mkdir(exist_ok=True)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
        pg = await b.new_page(viewport={'width': 1440, 'height': 880})
        errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto((ROOT / 'dist/index.html').as_uri()); await pg.wait_for_timeout(1500)
        await pg.screenshot(path=str(OUT/'01-title.png'))
        await pg.click('#t-new'); await pg.wait_for_timeout(400)
        await pg.evaluate("S.player.pelt='ginger'; S.player.pattern='tabby'; S.player.eyes='green'; S.player.pre='Ember'; S.player.suf='heart'; render()")
        await pg.wait_for_timeout(300); await pg.screenshot(path=str(OUT/'02-create.png'))
        await pg.click('#gobtn'); await pg.wait_for_timeout(300)
        await pg.click('[data-opt="0"]'); await pg.wait_for_timeout(200); await pg.click('#contbtn'); await pg.wait_for_timeout(500)
        await pg.screenshot(path=str(OUT/'03-hearts.png'))
        await pg.click('[data-opt="1"]'); await pg.wait_for_timeout(200); await pg.click('#contbtn')  # kindred
        await pg.click('[data-opt="0"]'); await pg.click('#contbtn')
        await pg.click('[data-opt="0"]'); await pg.click('#contbtn')
        await pg.wait_for_timeout(300); await pg.screenshot(path=str(OUT/'04-deputy.png'))
        await pg.click('[data-opt="0"]'); await pg.wait_for_timeout(200); await pg.click('#contbtn'); await pg.wait_for_timeout(300)
        # season intro
        await pg.screenshot(path=str(OUT/'05-season.png'))
        await pg.evaluate("S.scene=null; S.queue=[{k:'event',id:'kittypet'}]; processQueue()")
        await pg.wait_for_timeout(300); await pg.click('[data-adv="speckleback"]'); await pg.wait_for_timeout(300)
        await pg.screenshot(path=str(OUT/'06-event.png'))
        await pg.click('[data-opt="3"]'); await pg.wait_for_timeout(300)
        await pg.screenshot(path=str(OUT/'07-outcome.png'))
        await pg.evaluate("S.scene=null; S.queue=[]; S.tab='camp'; render()"); await pg.wait_for_timeout(400)
        await pg.screenshot(path=str(OUT/'08-camp.png'))
        await pg.evaluate("S.tab='territory'; S.zoneSel='thornmarsh'; render()"); await pg.wait_for_timeout(400)
        await pg.screenshot(path=str(OUT/'09-map.png'))
        await pg.evaluate("S.tab='clans'; render()"); await pg.wait_for_timeout(400)
        await pg.screenshot(path=str(OUT/'10-clans.png'))
        await pg.evaluate("S.queue=[{k:'gathering'}]; processQueue()"); await pg.wait_for_timeout(400)
        await pg.screenshot(path=str(OUT/'11-gathering.png'))
        await pg.evaluate("S.scene=null; S.legends=['leap']; S.queue=[{k:'walk',v:{id:'leap',step:1,wrong:0}}]; processQueue()"); await pg.wait_for_timeout(400)
        await pg.screenshot(path=str(OUT/'12-walk.png'))
        await pg.evaluate("S.scene=null; S.season=3; S.queue=[{k:'turning'}]; processQueue()"); await pg.wait_for_timeout(400)
        await pg.screenshot(path=str(OUT/'13-turning.png'))
        await pg.evaluate("S.scene=null; S.queue=[{k:'script',id:'dark1'}]; processQueue()"); await pg.wait_for_timeout(400)
        await pg.screenshot(path=str(OUT/'14-dark.png'))
        await pg.evaluate("S.scene=null; S.year=3; S.season=3; S.queue=[{k:'script',id:'finale1'}]; processQueue()"); await pg.wait_for_timeout(400)
        await pg.screenshot(path=str(OUT/'15-finale.png'))
        await pg.evaluate("S.scene=null; S.flags.leaderCouncil=true; S.queue=[{k:'ending',why:'unity'}]; processQueue()"); await pg.wait_for_timeout(400)
        await pg.screenshot(path=str(OUT/'16-ending.png'))
        m = await b.new_page(viewport={'width': 390, 'height': 844}, device_scale_factor=2)
        await m.goto((ROOT / 'dist/index.html').as_uri()); await m.wait_for_timeout(1200)
        await m.screenshot(path=str(OUT/'17-m-title.png'))
        await m.click('#t-new'); await m.wait_for_timeout(300)
        await m.screenshot(path=str(OUT/'18a-m-create.png'))
        await m.evaluate("S.player.heart='valiant'; S.deputy='oakfang'; S.flags.started=true; S.scene=null; S.year=1; S.season=1; S.queue=[{k:'event',id:'fox'}]; processQueue()"); await m.wait_for_timeout(500)
        await m.screenshot(path=str(OUT/'18-m-event.png'))
        print('errors', errs)
        await b.close()
asyncio.run(main())
